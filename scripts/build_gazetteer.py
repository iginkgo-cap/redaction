#!/usr/bin/env python3
"""S7 (round11): 从公开数据源构建英文人名 gazetteer。

生成物（入库、可再生，禁止手工编辑）：
  config/gazetteer/given_names_en.txt   英文 given name（SSA 官方数据镜像，public domain）
  config/gazetteer/surnames_en.txt      英文姓氏（US Census 2010，public domain）
  config/gazetteer/ambiguous_names.txt  歧义名（名字 ∩ 英文高频词，如 May/Will/June）
                                        —— 召回方向禁用，gate 方向仍算已知名

数据源（避免死名单：重跑本脚本即更新；来源均为 public domain / 公开仓库）：
  1. hadley/data-baby-names —— SSA babynames 每年 top1000（1880-2008）镜像 CSV。
     （ssa.gov/oact/babynames/names.zip 为原始源，其 CDN 拦脚本 UA 时用此镜像）
  2. www2.census.gov 2010surnames names.zip —— 美国人口普查姓氏排名。
  3. first20hours/google-10000-english —— 英文高频 1 万词（歧义交集用）。

用法：python3 scripts/build_gazetteer.py [--surname-top 40000] [--out-dir config/gazetteer]
"""
from __future__ import annotations

import argparse
import csv
import io
import sys
import urllib.request
import zipfile
from datetime import date
from pathlib import Path

SSA_MIRROR_CSV = (
    "https://raw.githubusercontent.com/hadley/data-baby-names/master/baby-names.csv"
)
CENSUS_SURNAMES_ZIP = (
    "https://www2.census.gov/topics/genealogy/2010surnames/names.zip"
)
GOOGLE_10K = (
    "https://raw.githubusercontent.com/first20hours/google-10000-english/master/"
    "google-10000-english.txt"
)
_UA = {"User-Agent": "Mozilla/5.0 (gazetteer-build; redaction-service round11)"}


def _fetch(url: str) -> bytes:
    req = urllib.request.Request(url, headers=_UA)
    with urllib.request.urlopen(req, timeout=120) as resp:
        return resp.read()


def build_given_names() -> set[str]:
    raw = _fetch(SSA_MIRROR_CSV).decode("utf-8")
    names = {
        row["name"].strip().lower()
        for row in csv.DictReader(io.StringIO(raw))
        if row.get("name", "").strip()
    }
    print(f"given names (SSA mirror): {len(names)}")
    return names


def build_surnames(top: int) -> set[str]:
    blob = _fetch(CENSUS_SURNAMES_ZIP)
    with zipfile.ZipFile(io.BytesIO(blob)) as zf:
        csv_name = next(n for n in zf.namelist() if n.endswith(".csv"))
        raw = zf.read(csv_name).decode("utf-8", errors="replace")
    surnames: set[str] = set()
    for row in csv.DictReader(io.StringIO(raw)):
        try:
            if int(row["rank"]) <= top:
                surnames.add(row["name"].strip().lower())
        except (KeyError, ValueError):
            continue
    print(f"surnames (Census 2010, top {top}): {len(surnames)}")
    return surnames


def _write(path: Path, values: set[str], source: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(f"# generated by scripts/build_gazetteer.py on {date.today()}\n")
        f.write(f"# source: {source}\n")
        f.write(f"# count: {len(values)}  —— 禁止手工编辑，更新请重跑脚本\n")
        for v in sorted(values):
            f.write(v + "\n")
    print(f"wrote {path} ({len(values)})")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--surname-top", type=int, default=40000)
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=Path(__file__).resolve().parent.parent / "config" / "gazetteer",
    )
    args = parser.parse_args()

    given = build_given_names()
    surnames = build_surnames(args.surname_top)
    common = {
        w.strip().lower()
        for w in _fetch(GOOGLE_10K).decode("utf-8").splitlines()
        if w.strip()
    }
    ambiguous = (given | surnames) & common
    print(f"ambiguous (names ∩ google-10000-english): {len(ambiguous)}")

    _write(args.out_dir / "given_names_en.txt", given, SSA_MIRROR_CSV)
    _write(
        args.out_dir / "surnames_en.txt",
        surnames,
        f"{CENSUS_SURNAMES_ZIP} (top {args.surname_top} by rank)",
    )
    _write(args.out_dir / "ambiguous_names.txt", ambiguous, GOOGLE_10K)
    # gate 方向用：常用英文词全集（precision 侧再与名单做差集——
    # 「常用词且非名字」才 drop，未知罕见 token 默认保留，见 app/gazetteer.py）
    _write(args.out_dir / "common_words_en.txt", common, GOOGLE_10K)
    return 0


if __name__ == "__main__":
    sys.exit(main())
